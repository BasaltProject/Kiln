#!/usr/bin/env python3
"""Emits the raw import declarations of every ABI area for each SDK language.

Reads wire/wire-wasm/abi/areas/*.h (the normative headers) and writes sdk/<lang>/generated/... so the people adding an
area write only idiomatic wrappers. The core ABI (basalt_abi.h, basalt_proxy_abi.h) stays hand-written in each SDK.
Also writes the small index files that list the areas and the wrappers present, which are regenerated, never edited.

    python3 scripts/gen-sdk.py            write the files
    python3 scripts/gen-sdk.py --check    fail when a committed file differs (CI)
"""
import argparse
import re
import sys
from pathlib import Path

HEADER = "Generated by scripts/gen-sdk.py from wire/wire-wasm/abi/areas/{area}.h. Do not edit."
MACRO = re.compile(
    r"(BASALT_IMPORT_SHARED|BASALT_IMPORT|BASALT_PROXY_IMPORT)\(([a-z0-9_]+)\)\s+([a-z0-9_]+)\s+(basalt_[a-z0-9_]+)\(([^)]*)\)",
    re.S)
BASE = {"char": "u8", "void": "u8", "int32_t": "i32", "int64_t": "i64", "float": "f32", "double": "f64"}


class Param:
    def __init__(self, text, index):
        text = text.strip()
        self.pointer = "*" in text
        self.const = text.startswith("const ")
        words = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text.replace("const", ""))
        self.base = BASE[words[0]]
        self.name = words[1] if len(words) > 1 else "p%d" % index


class Import:
    def __init__(self, macro, name, ret, params):
        self.module = "basalt_proxy" if macro == "BASALT_PROXY_IMPORT" else "basalt"
        self.name = name
        self.ret = None if ret == "void" else BASE[ret]
        text = params.strip()
        self.params = [] if text in ("", "void") else [Param(p, i) for i, p in enumerate(text.split(","))]
        self.shared = macro == "BASALT_IMPORT_SHARED"
        self.symbol = ("basalt_proxy_" if self.module == "basalt_proxy" else "basalt_") + name


def parse(path):
    text = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
    return [Import(m[1], m[2], m[3], m[5]) for m in MACRO.finditer(text)]


def pascal(name):
    return "".join(part.capitalize() for part in name.split("_"))


def rawname(i):
    return "raw" + ("Proxy" if i.module == "basalt_proxy" else "") + pascal(i.name)


def camel(name):
    p = pascal(name)
    return p[0].lower() + p[1:]


def safe(name, reserved):
    return name + "_" if name in reserved else name


def lang_zig(area, imports):
    def ty(p):
        return ("[*]const " if p.const else "[*]") + p.base if p.pointer else p.base
    out = ["// " + HEADER.format(area=area), "pub const raw = struct {"]
    for i in imports:
        args = ", ".join("%s: %s" % (safe(p.name, {"type", "error", "align", "var", "fn", "test"}), ty(p)) for p in i.params)
        out.append('    pub extern "%s" fn %s(%s) %s;' % (i.module, i.name, args, i.ret or "void"))
    out.append("};")
    return "\n".join(out) + "\n"


def lang_rust(area, imports):
    def ty(p):
        return ("*const " if p.const else "*mut ") + p.base if p.pointer else p.base
    out = ["// " + HEADER.format(area=area), "#![allow(dead_code)]"]
    for module in ("basalt", "basalt_proxy"):
        group = [i for i in imports if i.module == module]
        if not group:
            continue
        out += ['#[link(wasm_import_module = "%s")]' % module, 'extern "C" {']
        for i in group:
            args = ", ".join("%s: %s" % (safe(p.name, {"type", "fn", "mod", "ref", "in", "match", "move"}), ty(p)) for p in i.params)
            out.append("    pub fn %s(%s)%s;" % (i.name, args, " -> " + i.ret if i.ret else ""))
        out.append("}")
    return "\n".join(out) + "\n"


def lang_go(area, imports):
    gotype = {"u8": "byte", "i32": "int32", "i64": "int64", "f32": "float32", "f64": "float64"}
    keys = {"type", "func", "range", "var", "go", "map", "chan", "select", "package", "import", "interface", "struct"}
    out = ["// " + HEADER.format(area=area), "", "package basalt", ""]
    for i in imports:
        args = ", ".join("%s %s%s" % (safe(p.name, keys), "*" if p.pointer else "", gotype[p.base]) for p in i.params)
        out += ["//go:wasmimport %s %s" % (i.module, i.name),
                "func %s(%s)%s" % (rawname(i), args, " " + gotype[i.ret] if i.ret else ""), ""]
    return "\n".join(out)


def lang_java(area, imports):
    jt = {"i32": "int", "i64": "long", "f32": "float", "f64": "double"}
    keys = {"int", "long", "new", "class", "this", "default", "char", "byte", "short", "final", "package", "native"}
    out = ["// " + HEADER.format(area=area), "package basalt;", "", "import org.teavm.interop.Address;",
           "import org.teavm.interop.Import;", "", "final class Raw%s {" % pascal(area), "    private Raw%s() {}" % pascal(area), ""]
    for i in imports:
        args = ", ".join("%s %s" % ("Address" if p.pointer else jt[p.base], safe(p.name, keys)) for p in i.params)
        out.append('    @Import(name = "%s") static native %s raw%s(%s);' % (i.symbol, jt[i.ret] if i.ret else "void", pascal(i.name), args))
    out.append("}")
    return "\n".join(out) + "\n"


def lang_kotlin(area, imports):
    kt = {"i32": "Int", "i64": "Long", "f32": "Float", "f64": "Double"}
    keys = {"val", "var", "fun", "in", "is", "object", "when", "class", "typeof"}
    out = ["@file:OptIn(kotlin.wasm.unsafe.UnsafeWasmMemoryApi::class, kotlin.wasm.ExperimentalWasmInterop::class)", "",
           "// " + HEADER.format(area=area), "package basalt", "", "import kotlin.wasm.WasmImport", ""]
    for i in imports:
        args = ", ".join("%s: %s" % (safe(p.name, keys), "Int" if p.pointer else kt[p.base]) for p in i.params)
        out += ['@WasmImport("%s", "%s")' % (i.module, i.name),
                "internal external fun %s(%s)%s" % (rawname(i), args, ": " + kt[i.ret] if i.ret else ""), ""]
    return "\n".join(out)


def lang_csharp(area, imports):
    cs = {"i32": "int", "i64": "long", "f32": "float", "f64": "double", "u8": "byte"}
    keys = {"out", "ref", "in", "int", "long", "string", "object", "params", "event", "base", "lock", "checked"}
    out = ["// " + HEADER.format(area=area), "using System.Runtime.InteropServices;", "",
           "internal static unsafe class Raw%s" % pascal(area), "{"]
    for i in imports:
        args = ", ".join("%s%s %s" % (cs[p.base], "*" if p.pointer else "", safe(p.name, keys)) for p in i.params)
        out += ['    [WasmImportLinkage, DllImport("%s", EntryPoint = "%s")]' % (i.module, i.name),
                "    internal static extern %s %s(%s);" % (cs[i.ret] if i.ret else "void", pascal(i.name), args)]
    out.append("}")
    return "\n".join(out) + "\n"


def lang_as(area, imports):
    at = {"i32": "i32", "i64": "i64", "f32": "f32", "f64": "f64"}
    keys = {"in", "out", "var", "let", "type", "default", "new", "delete"}
    out = ["// " + HEADER.format(area=area), "", "export namespace raw_%s {" % area]
    for i in imports:
        args = ", ".join("%s: %s" % (safe(p.name, keys), "usize" if p.pointer else at[p.base]) for p in i.params)
        out += ["  // @ts-ignore: decorator",
                '  @external("%s", "%s") export declare function %s(%s): %s;' % (i.module, i.name, i.name, args, at[i.ret] if i.ret else "void")]
    out.append("}")
    return "\n".join(out) + "\n"


LANGS = {"zig": lang_zig, "rust": lang_rust, "go": lang_go, "java": lang_java,
         "kotlin": lang_kotlin, "csharp": lang_csharp, "assemblyscript": lang_as}


def profiles(imports):
    if imports and all(i.shared for i in imports):
        return ("server", "proxy")
    return ("proxy",) if any(i.module == "basalt_proxy" for i in imports) else ("server",)


def indexes(sdk, areas):
    """Index files that list what exists; the single place a language needs a list."""
    files = {}
    abi = "".join('#include "areas/%s.h"\n' % a for a in areas)
    for root in ("server", "proxy"):
        files["c/basalt/%s.h" % root] = ("/* Generated by scripts/gen-sdk.py. Do not edit. Every header of basalt/%s/. */\n" % root +
            "#ifndef BASALT_%s_H\n#define BASALT_%s_H\n\n" % (root.upper(), root.upper()) +
            "".join('#include "basalt/%s/%s"\n' % (root, h.name) for h in sorted((sdk / "c/basalt" / root).glob("*.h"))) + "\n#endif\n")
    files["java/glue/generated/basalt_java_areas.h"] = "/* Generated by scripts/gen-sdk.py. Do not edit. */\n#pragma once\n" + abi
    return files


def main():
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser()
    parser.add_argument("--abi-dir", default=str(root / "wire/wire-wasm/abi"))
    parser.add_argument("--sdk-dir", default=str(root / "sdk"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sdk = Path(args.sdk_dir)
    headers = sorted(Path(args.abi_dir, "areas").glob("*.h"))
    areas = [h.stem for h in headers]
    files = {}
    for header in headers:
        imports = parse(header)
        for lang, gen in LANGS.items():
            if lang == "csharp":
                for profile in profiles(imports):
                    text = gen(header.stem, imports)
                    lines = text.splitlines()
                    at = next(i for i, line in enumerate(lines) if line.startswith("internal "))
                    lines.insert(at, "namespace Basalt.%s.Internal;" % profile.capitalize())
                    files["csharp/%s/Internal/Raw%s.cs" % (profile, pascal(header.stem))] = "\n".join(lines) + "\n"
            elif lang == "go":
                for profile in profiles(imports):
                    files["go/%s/internal/runtime/zz_%s_raw.go" % (profile, header.stem)] = gen(header.stem, imports).replace("package basalt", "package runtime")
            elif lang == "rust":
                for profile in profiles(imports):
                    area = header.stem.removeprefix("proxy_")
                    files["rust/basalt_%s/raw/%s.rs" % (profile, area)] = gen(header.stem, imports)
            elif lang == "assemblyscript":
                module = "basalt-proxy" if header.stem.startswith("proxy_") else "basalt-internal" if header.stem == "core_values" else "basalt-server"
                area = header.stem.removeprefix("proxy_")
                files["assemblyscript/%s/raw/%s.ts" % (module, area)] = gen(header.stem, imports)
            elif lang == "zig":
                module = "basalt_proxy" if header.stem.startswith("proxy_") else "basalt_shared" if all(i.shared for i in imports) else "basalt_server"
                files["zig/%s/raw/%s.zig" % (module, header.stem)] = gen(header.stem, imports)
            elif lang == "kotlin":
                for profile in profiles(imports):
                    text = gen(header.stem, imports).replace("package basalt", "package org.basaltmc." + profile + ".internal")
                    files["kotlin/%s/internal/%sRaw.kt" % (profile, pascal(header.stem))] = text
            elif lang == "java":
                for profile in profiles(imports):
                    package = "org.basaltmc." + profile + ".internal"
                    text = gen(header.stem, imports).replace("package basalt;", "package " + package + ";")
                    text = text.replace("final class Raw", "public final class Raw").replace(" static native ", " public static native ")
                    files["java/%s/%s/Raw%s.java" % (profile, package.replace(".", "/"), pascal(header.stem))] = text
    for source in (sdk / "java/shared").rglob("*.java.in"):
        for profile in ("server", "proxy"):
            relative = source.relative_to(sdk / "java/shared").as_posix()[:-3]
            files["java/%s/org/basaltmc/%s/%s" % (profile, profile, relative)] = source.read_text().replace("org.basaltmc.shared", "org.basaltmc." + profile)
    for source in (sdk / "kotlin/shared").rglob("*.kt.in"):
        for profile in ("server", "proxy"):
            relative = source.relative_to(sdk / "kotlin/shared").as_posix()[:-3]
            files["kotlin/%s/%s" % (profile, relative)] = source.read_text().replace("org.basaltmc.shared", "org.basaltmc." + profile)
    for profile in ("server", "proxy"):
        path = sdk / ("rust/basalt_%s/raw/mod.rs" % profile)
        base = path.read_text().split("// Generated area modules")[0]
        base += "// Generated area modules\n"
        base += "".join("pub mod %s;\n" % a.removeprefix("proxy_") for a in areas if a == "core_values" or a.startswith("proxy_") == (profile == "proxy"))
        files[str(path.relative_to(sdk))] = base
    for source in (sdk / "go/shared").glob("*.go.in"):
        stem = source.name.removesuffix(".go.in")
        for profile in ("server", "proxy"):
            if stem not in ("basalt", "values") and stem.startswith("proxy") != (profile == "proxy"):
                continue
            files["go/%s/internal/runtime/%s.go" % (profile, stem)] = source.read_text()
    for source in (sdk / "csharp/shared").rglob("*.cs.in"):
        for profile in ("server", "proxy"):
            relative = source.relative_to(sdk / "csharp/shared").as_posix()[:-3]
            files["csharp/%s/Shared/%s" % (profile, relative)] = source.read_text().replace("Basalt.Shared", "Basalt." + profile.capitalize())
    for source in (sdk / "cpp/shared").glob("*.hpp.in"):
        for profile in ("server", "proxy"):
            text = source.read_text().replace("basalt/shared", "basalt/" + profile).replace("basalt::shared", "basalt::" + profile)
            files["cpp/basalt/%s/%s" % (profile, source.name[:-3])] = text
    files.update(indexes(sdk, areas))
    bad = 0
    for relative, text in sorted(files.items()):
        text = "\n".join(line.rstrip() for line in text.splitlines()).rstrip() + "\n"
        path = sdk / relative
        if args.check:
            if not path.exists() or path.read_text() != text:
                print("out of date: " + str(path))
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
    for stale in sdk.rglob("*"):
        if stale.is_file() and stale.suffix in {".java", ".kt", ".cs", ".go", ".rs", ".zig", ".ts", ".h", ".hpp"}:
            if str(stale.relative_to(sdk)) not in files and "Generated by scripts/gen-sdk.py" in stale.read_text():
                if args.check:
                    print("stale: " + str(stale))
                    bad += 1
                else:
                    stale.unlink()
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
