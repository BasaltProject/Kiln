class CSharp(Lang):
    key = "csharp"
    wrapper = "sdk/csharp/server/Worlds/WorldManager.cs"
    TY = {"i32": "int", "i64": "long", "f32": "float", "f64": "double"}

    def fn(self, imp, owner, items):
        params, raw, fixed = [], [], []
        arr = first_array(items)
        rawcls = "RawWorlds" if owner == "worlds" else "RawCoreValues"
        for kind, name, extra in items:
            if kind in self.TY:
                params.append("%s %s" % (self.TY[kind], name)); raw.append(name)
            elif kind == "str":
                params.append("string %s" % name)
                fixed.append("byte[] %sB = Utf8(%s);" % (name, name))
                fixed.append("fixed (byte* %sP = %sB)" % (name, name)); raw += ["%sP" % name, "%sB.Length" % name]
            elif kind in ("bytes", "out"):
                params.append("byte[] %s" % name)
                fixed.append("fixed (byte* %sP = %s)" % (name, name)); raw += ["%sP" % name, "%s.Length" % name]
            elif kind == "ints":
                params.append("int[] %s" % name)
                fixed.append("fixed (int* %sP = %s)" % (name, name)); raw.append("%sP" % name)
            elif kind == "count":
                raw.append("%s.Length / %d" % (arr, stride_of(arr)))
            elif kind == "intsout":
                params.append("int[] %s" % name)
                fixed.append("fixed (int* %sP = %s)" % (name, name)); raw.append("%sP" % name)
                if extra:
                    raw.append("%s.Length" % name)
            elif kind == "f64out":
                params.append("double[] %s" % name)
                fixed.append("fixed (double* %sP = %s)" % (name, name)); raw.append("%sP" % name)
            elif kind == "handler":
                params.append("Handler done"); raw.append("Basalt.TokenFor(done)")
        lines = [f for f in fixed if f.startswith("byte[]")]
        fx = [f for f in fixed if not f.startswith("byte[]")]
        body = "".join("        %s\n" % l for l in lines)
        for f in fx:
            body += "        %s\n" % f
        indent = "            " if fx else "        "
        return "    public static int %s(%s)\n    {\n%s%sreturn %s.%s(%s);\n    }\n\n" % (
            pascal(public_name(imp, owner)), ", ".join(params), body, indent, rawcls, pascal(imp.name), ", ".join(raw))

    def head(self):
        return ("// " + HEADER + "\nusing System;\nusing System.Text;\n\npublic static unsafe class Worlds\n{\n"
                "    public const int Load = 1, Notify = 2, Resend = 4, Generate = 8;\n\n"
                "    static byte[] Utf8(string text) => Encoding.UTF8.GetBytes(text);\n\n"
                "    public static int ChunkCoord(int block) => block >> 4;\n\n"
                "    public static double BlockDistance(int x1, int y1, int z1, int x2, int y2, int z2)\n    {\n        double dx = x2 - x1, dy = y2 - y1, dz = z2 - z1;\n        return Math.Sqrt(dx * dx + dy * dy + dz * dz);\n    }\n\n"
                "    public static void PosOffset(int[] pos, int dx, int dy, int dz)\n    {\n        pos[0] += dx;\n        pos[1] += dy;\n        pos[2] += dz;\n    }\n\n")

    def tail(self):
        return "}\n"


class AS(Lang):
    key = "assemblyscript"
    wrapper = "sdk/assemblyscript/basalt-server/worlds.ts"
    TY = {"i32": "i32", "i64": "i64", "f32": "f32", "f64": "f64"}

    def fn(self, imp, owner, items):
        params, raw, pre = [], [], ""
        arr = first_array(items)
        rawns = "raw" if owner == "worlds" else "core"
        for kind, name, extra in items:
            if kind in self.TY:
                params.append("%s: %s" % (name, self.TY[kind])); raw.append(name)
            elif kind == "str":
                pre += "  const %sB = String.UTF8.encode(%s);\n" % (name, name)
                params.append("%s: string" % name); raw += ["changetype<usize>(%sB)" % name, "%sB.byteLength" % name]
            elif kind in ("bytes", "out"):
                params.append("%s: Uint8Array" % name); raw += ["changetype<usize>(%s.dataStart)" % name, "%s.length" % name]
            elif kind == "ints":
                params.append("%s: Int32Array" % name); raw.append("changetype<usize>(%s.dataStart)" % name)
            elif kind == "count":
                raw.append("%s.length / %d" % (arr, stride_of(arr)))
            elif kind == "intsout":
                params.append("%s: Int32Array" % name); raw.append("changetype<usize>(%s.dataStart)" % name)
                if extra:
                    raw.append("%s.length" % name)
            elif kind == "f64out":
                params.append("%s: Float64Array" % name); raw.append("changetype<usize>(%s.dataStart)" % name)
            elif kind == "handler":
                params.append("done: Handler"); raw.append("tokenFor(done)")
        return "export function %s(%s): i32 {\n%s  return %s.%s(%s);\n}\n\n" % (
            camel(public_name(imp, owner)), ", ".join(params), pre, rawns, imp.name, ", ".join(raw))

    def head(self):
        return ("// " + HEADER + "\nimport { raw_worlds as raw } from \"../generated/worlds\";\nimport { raw_core_values as core } from \"../generated/core_values\";\n"
                "import { tokenFor, Handler } from \"../index\";\n\n"
                "export const WORLD_LOAD: i32 = 1;\nexport const WORLD_NOTIFY: i32 = 2;\nexport const WORLD_RESEND: i32 = 4;\nexport const WORLD_GENERATE: i32 = 8;\n\n"
                "export function chunkCoord(block: i32): i32 {\n  return block >> 4;\n}\n\n"
                "export function blockDistance(x1: i32, y1: i32, z1: i32, x2: i32, y2: i32, z2: i32): f64 {\n  const dx = <f64>(x2 - x1);\n  const dy = <f64>(y2 - y1);\n  const dz = <f64>(z2 - z1);\n  return Math.sqrt(dx * dx + dy * dy + dz * dz);\n}\n\n"
                "export function posOffset(pos: Int32Array, dx: i32, dy: i32, dz: i32): void {\n  pos[0] += dx;\n  pos[1] += dy;\n  pos[2] += dz;\n}\n\n")

    def tail(self):
        return ""


LANGS = [C(), Cpp(), Zig(), Rust(), Go(), Java(), Kotlin(), CSharp(), AS()]


def wrapper_text(lang, imports):
    body = "".join(lang.fn(imp, owner, plan(imp)) + ("\n" if lang.key in ("c", "cpp", "zig", "rust", "go", "kotlin") else "")
                   for imp, owner in imports)
    return lang.head() + body + lang.tail()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--examples")
    args = parser.parse_args()
    imports = load_imports()
    bad = 0
    for lang in LANGS:
        path = ROOT / lang.wrapper
        text = wrapper_text(lang, imports)
        if lang.key == "csharp":
            text = text.replace("Basalt.Handler", "Handler").replace("Basalt.", "Native.")
            text = text.replace("public static unsafe class Worlds", "using Basalt.Server.Core;\nusing Basalt.Server.Internal;\nnamespace Basalt.Server.Worlds;\npublic static unsafe class Worlds")
        if lang.key == "go":
            text = text.replace("package basalt", "package runtime")
        if lang.key == "rust":
            text = text.replace("super::raw_core_values", "crate::raw::core_values").replace("super::raw_worlds", "crate::raw::worlds").replace("use crate::{token_for, Ctx}", "use crate::core::{token_for, Ctx}")
        if lang.key == "assemblyscript":
            text = text.replace("../generated/worlds", "./raw/worlds").replace("../generated/core_values", "../basalt-internal/raw/core_values").replace("../index", "../basalt-internal/index")
        if lang.key == "cpp":
            text = text.replace('#include "values.hpp"', '#include <basalt/server/values.hpp>\n#include <basalt/server/worlds.h>\n#include <basalt/server/core.hpp>')
            text = text.replace("namespace basalt::worlds {", "namespace basalt::server::worlds {\nusing namespace basalt::server::core;")
        if lang.key == "kotlin":
            text = text.replace("package basalt", "package org.basaltmc.server.worlds\nimport org.basaltmc.server.core.*\nimport org.basaltmc.server.internal.*")
        if lang.key == "java":
            from sdk_layout import java_wrapper
            text = java_wrapper(text, "worlds")
        if lang.key == "java":
            from source_imports import java_imports
            text = java_imports(text.replace("class Worlds", "class WorldManager").replace("private Worlds()", "private WorldManager()"))
        elif lang.key == "kotlin":
            from source_imports import kotlin_imports
            text = kotlin_imports(text)
        elif lang.key == "csharp":
            from source_imports import csharp_imports
            text = csharp_imports(text.replace("class Worlds", "class WorldManager"))
        text = "\n".join(line.rstrip() for line in text.splitlines()).rstrip() + "\n"
        if args.check:
            if not path.exists() or path.read_text() != text:
                print("out of date: " + str(path))
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.examples:
        import tour
        tour.write(Path(args.examples), imports, plan, sys.modules[__name__])
    return 1 if bad else 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    sys.exit(main())
