class C(Lang):
    key = "c"
    wrapper = "sdk/c/basalt/server/worlds.h"
    TY = {"i32": "int32_t", "i64": "int64_t", "f32": "float", "f64": "double"}

    def fname(self, n):
        return "bs_" + n

    def fn(self, imp, owner, items):
        params, raw = [], []
        for kind, name, extra in items:
            if kind in self.TY:
                params.append("%s %s" % (self.TY[kind], name)); raw.append(name)
            elif kind == "str":
                params.append("const char *%s" % name); raw += [name, "bs_wtext(%s)" % name]
            elif kind == "bytes":
                params.append("const void *%s, int32_t %s" % (name, extra)); raw += ["(const char *)%s" % name, extra]
            elif kind == "out":
                params.append("char *%s, int32_t %s" % (name, extra)); raw += [name, extra]
            elif kind == "ints":
                params.append("const int32_t *%s" % name); raw.append(name)
            elif kind == "count":
                params.append("int32_t count"); raw.append("count")
            elif kind == "intsout":
                params.append("int32_t *%s" % name); raw.append(name)
                if extra:
                    params.append("int32_t cap"); raw.append("cap")
            elif kind == "f64out":
                params.append("double *%s" % name); raw.append(name)
            elif kind == "handler":
                params.append("bs_handler done"); raw.append("token")
        pre = ""
        call = "basalt_%s(%s)" % (imp.name, ", ".join(raw))
        if any(k == "handler" for k, _, _ in items):
            pre = "    const int32_t token = bs_once_token(done);\n    if (token <= 0) {\n        return BASALT_ERR_INVALID;\n    }\n"
            call = "bs_once_bind(token, BS_ONCE_REQUEST, %s)" % call
        elif imp.name == "request_cancel":
            call = "bs_request_cancel(%s)" % ", ".join(raw)
        return "static inline int32_t %s(%s) {\n%s    return %s;\n}\n" % (
            self.fname(public_name(imp, owner)), ", ".join(params), pre, call)

    def head(self):
        return ("/* " + HEADER + " */\n#ifndef BASALT_SERVER_WORLDS_H\n#define BASALT_SERVER_WORLDS_H\n\n"
                "#include \"basalt/server/core.h\"\n#include \"basalt/server/values.h\"\n#include \"areas/worlds.h\"\n\n"
                "#define BS_WORLD_LOAD 1\n#define BS_WORLD_NOTIFY 2\n#define BS_WORLD_RESEND 4\n#define BS_WORLD_GENERATE 8\n\n"
                "static inline int32_t bs_wtext(const char *text) {\n    int32_t n = 0;\n    while (text != 0 && text[n]) {\n        ++n;\n    }\n    return n;\n}\n\n"
                "static inline int32_t bs_chunk_coord(int32_t block) { return block >> 4; }\n\n"
                "static inline double bs_block_distance(int32_t x1, int32_t y1, int32_t z1, int32_t x2, int32_t y2, int32_t z2) {\n"
                "    const double dx = (double)x2 - x1, dy = (double)y2 - y1, dz = (double)z2 - z1;\n    return __builtin_sqrt(dx * dx + dy * dy + dz * dz);\n}\n\n"
                "static inline void bs_pos_offset(int32_t *pos, int32_t dx, int32_t dy, int32_t dz) {\n    pos[0] += dx;\n    pos[1] += dy;\n    pos[2] += dz;\n}\n\n")

    def tail(self):
        return "\n#endif\n"


class Cpp(Lang):
    key = "cpp"
    wrapper = "sdk/cpp/basalt/server/worlds.hpp"

    def fn(self, imp, owner, items):
        n = public_name(imp, owner)
        c = C()
        text = c.fn(imp, owner, items)
        sig = text.split("{", 1)[0]
        params = sig[sig.index("(") + 1:sig.rindex(")")]
        names = []
        for kind, name, extra in items:
            if kind == "bytes":
                names += [name, extra]
            elif kind == "out":
                names += [name, extra]
            elif kind == "intsout":
                names += [name] + (["cap"] if extra else [])
            elif kind == "handler":
                names.append("done")
            else:
                names.append(name)
        params = params.replace("bs_handler", "Handler")
        return "inline int32_t %s(%s) { return bs_%s(%s); }\n" % (n, params, n, ", ".join(names))

    def head(self):
        return ("// " + HEADER + "\n#pragma once\n\n#include \"values.hpp\"\n\nnamespace basalt::worlds {\n\n"
                "enum Flags { kLoad = BS_WORLD_LOAD, kNotify = BS_WORLD_NOTIFY, kResend = BS_WORLD_RESEND, kGenerate = BS_WORLD_GENERATE };\n\n"
                "inline int32_t chunk_coord(int32_t block) { return bs_chunk_coord(block); }\n\n"
                "inline double block_distance(int32_t x1, int32_t y1, int32_t z1, int32_t x2, int32_t y2, int32_t z2) {\n    return bs_block_distance(x1, y1, z1, x2, y2, z2);\n}\n\n"
                "inline void pos_offset(int32_t* pos, int32_t dx, int32_t dy, int32_t dz) { bs_pos_offset(pos, dx, dy, dz); }\n\n")

    def tail(self):
        return "\n} // namespace basalt::worlds\n"


