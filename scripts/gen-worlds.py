#!/usr/bin/env python3
"""Emits the worlds area wrappers (every import of worlds.h) for the nine SDK languages, and the worlds tour that the
example plugins run in their trace scenario.

    python3 scripts/gen-worlds.py --check             fail when a committed wrapper is out of date
    python3 scripts/gen-worlds.py                     write the wrappers into sdk/
    python3 scripts/gen-worlds.py --examples <dir>    also write the tour into <dir>/ServerPlugin-Example-worlds-<lang>
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("gensdk", ROOT / "scripts/gen-sdk.py")
gensdk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gensdk)

BYTES_NAMES = {"nbt", "nibbles", "args", "spec"}
STRIDE = {"positions": 3, "sources": 3, "chunks": 2}
HEADER = "Generated by scripts/gen-worlds.py from wire/wire-wasm/abi/areas/worlds.h. Do not edit."


def load_imports():
    abi = ROOT / "wire/wire-wasm/abi/areas"
    worlds = [(i, "worlds") for i in gensdk.parse(abi / "worlds.h")]
    core = [(i, "core") for i in gensdk.parse(abi / "core_values.h") if i.name in ("value_result", "request_cancel")]
    return worlds + core


def plan(imp):
    items, params, i = [], imp.params, 0
    while i < len(params):
        p = params[i]
        if p.pointer and p.base == "u8":
            length = params[i + 1].name
            kind = ("bytes" if p.name in BYTES_NAMES or (imp.name == "world_set" and p.name == "value") else "str") if p.const else "out"
            items.append((kind, p.name, length))
            i += 2
        elif p.pointer and p.base == "i32":
            if p.const:
                items.append(("ints", p.name, None))
                i += 1
            else:
                cap = i + 1 < len(params) and params[i + 1].name == "cap"
                items.append(("intsout", p.name, "cap" if cap else None))
                i += 2 if cap else 1
        elif p.pointer and p.base == "f64":
            items.append(("f64out", p.name, None))
            i += 1
        elif p.name == "count":
            items.append(("count", "count", None))
            i += 1
        elif p.name == "token":
            items.append(("handler", "done", None))
            i += 1
        else:
            items.append((p.base, p.name, None))
            i += 1
    return [(k, RENAME.get(n, n), e) for k, n, e in items]


RENAME = {"type": "kind", "out": "buffer", "in": "input", "fn": "func", "ref": "reference", "string": "text", "event": "eventId"}


def first_array(items):
    for kind, name, _ in items:
        if kind == "ints":
            return name
    return None


def stride_of(name):
    return STRIDE.get(name, 1)


def words(name):
    return name.split("_")


def camel(name):
    w = words(name)
    return w[0] + "".join(x.capitalize() for x in w[1:])


def pascal(name):
    return "".join(x.capitalize() for x in words(name))


def public_name(imp, owner):
    return ("world_" + imp.name) if owner == "core" else imp.name


